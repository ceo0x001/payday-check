-- ============================================================================
-- The 6-Minute Payday Check — initial schema
--
-- Design notes:
--   * One row per answer, written as it happens. Partial completions stay
--     fully analysable; drop-offs are respondents, not losses.
--   * `value` is jsonb + `question_version`. Question wording *will* change,
--     and this lets the instrument evolve without migrations or silently
--     corrupted longitudinal analysis.
--   * RLS is enabled with NO anon policies at all — deny by default. The
--     browser never touches Supabase; every write goes through a Next.js
--     route handler using the service-role key, which bypasses RLS.
-- ============================================================================

create extension if not exists "pgcrypto";
create extension if not exists "citext";

-- ---------------------------------------------------------------- sessions
create table if not exists public.sessions (
  id               uuid primary key default gen_random_uuid(),
  currency         text not null check (currency in ('NGN', 'USD')),
  locale           text,
  cycle_days       smallint,

  utm_source       text,
  utm_medium       text,
  utm_campaign     text,
  utm_content      text,
  referrer         text,

  device_class     text,
  -- Salted one-way hash. We never store an IP address.
  ua_hash          text,

  started_at       timestamptz not null default now(),
  completed_at     timestamptz,
  duration_ms      integer,
  resumed_count    smallint not null default 0,
  -- Where an abandoned session stopped: the drop-off signal.
  last_question_id text
);

create index if not exists sessions_started_at_idx  on public.sessions (started_at desc);
create index if not exists sessions_completed_idx   on public.sessions (completed_at)
  where completed_at is not null;
create index if not exists sessions_last_q_idx      on public.sessions (last_question_id);

-- ---------------------------------------------------------------- answers
create table if not exists public.answers (
  id               bigserial primary key,
  session_id       uuid not null references public.sessions (id) on delete cascade,
  question_id      text not null,
  question_version smallint not null default 1,
  value            jsonb not null,
  dwell_ms         integer,
  -- Revisions, not indecision: a high value means the question is unclear.
  change_count     smallint not null default 0,
  skipped          boolean not null default false,
  answered_at      timestamptz not null default now(),
  unique (session_id, question_id)
);

create index if not exists answers_question_idx on public.answers (question_id);
create index if not exists answers_session_idx  on public.answers (session_id);
create index if not exists answers_value_gin    on public.answers using gin (value);

-- ---------------------------------------------------------------- results
create table if not exists public.results (
  session_id          uuid primary key references public.sessions (id) on delete cascade,
  archetype           text not null,
  secondary_archetype text,
  cycle_days          smallint,
  squeeze_day         smallint,
  runway_pct          numeric(4, 3),
  tight_days          smallint,
  -- The research deliverable: which of the six competing explanations this
  -- respondent supports. Stored, never shown to the user.
  hypothesis_signal   text not null,
  signals             jsonb not null default '{}'::jsonb,
  headline            text,
  computed_at         timestamptz not null default now(),

  constraint results_archetype_chk check (archetype in (
    'steady_hand','tightrope','treadmill','provider','ambush','front_loader','slow_leak'
  )),
  constraint results_hypothesis_chk check (hypothesis_signal in (
    'H1_visibility','H2_adequacy','H3_lumpiness','H4_obligation','H5_regulation','H6_treadmill'
  ))
);

create index if not exists results_archetype_idx  on public.results (archetype);
create index if not exists results_hypothesis_idx on public.results (hypothesis_signal);

-- ---------------------------------------------------------------- waitlist
create table if not exists public.waitlist (
  id              bigserial primary key,
  session_id      uuid references public.sessions (id) on delete set null,
  email           citext not null unique,
  first_name      text,
  -- The metric that actually matters. Emails are vanity; conversations aren't.
  wants_interview boolean not null default false,
  currency        text check (currency in ('NGN', 'USD')),
  -- A real queue position, generated by the database. Never invented.
  position        integer generated always as identity,
  created_at      timestamptz not null default now()
);

create index if not exists waitlist_interview_idx on public.waitlist (wants_interview)
  where wants_interview;

-- ---------------------------------------------------------------- events
create table if not exists public.events (
  id         bigserial primary key,
  session_id uuid references public.sessions (id) on delete cascade,
  name       text not null,
  props      jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists events_name_idx    on public.events (name, created_at desc);
create index if not exists events_session_idx on public.events (session_id);

-- ============================================================================
-- Row Level Security — enabled, with no policies.
--
-- This is intentional and stricter than the usual anon-key pattern: with RLS
-- on and zero policies, the anon and authenticated roles can do nothing at
-- all. Only the service-role key (server-side, in route handlers) has access.
-- ============================================================================

alter table public.sessions enable row level security;
alter table public.answers  enable row level security;
alter table public.results  enable row level security;
alter table public.waitlist enable row level security;
alter table public.events   enable row level security;

revoke all on public.sessions, public.answers, public.results,
                public.waitlist, public.events
  from anon, authenticated;

-- ============================================================================
-- Analysis views
-- ============================================================================

-- 1. THE ONE THAT DECIDES THE COMPANY.
--    If H1_visibility is not dominant, the founding hypothesis is wrong —
--    and this tells you which of the other five is right.
create or replace view public.v_hypothesis_distribution as
select
  hypothesis_signal,
  count(*)                                          as respondents,
  round(100.0 * count(*) / nullif(sum(count(*)) over (), 0), 1) as pct
from public.results
group by hypothesis_signal
order by respondents desc;

-- 2. Drop-off by question — this is what iterates the instrument itself.
--    Any question above ~8% drop-off gets rewritten or cut.
create or replace view public.v_dropoff_by_question as
select
  last_question_id                                   as question_id,
  count(*)                                           as abandoned_here,
  round(100.0 * count(*) / nullif(sum(count(*)) over (), 0), 1) as pct_of_dropoffs
from public.sessions
where completed_at is null
  and last_question_id is not null
group by last_question_id
order by abandoned_here desc;

-- 3. Question health: dwell time, revision rate, skip rate.
--    High change_count means the *question* is ambiguous, not the respondent.
create or replace view public.v_question_health as
select
  question_id,
  count(*)                                     as responses,
  round(avg(dwell_ms) / 1000.0, 1)             as avg_seconds,
  round(avg(change_count)::numeric, 2)         as avg_revisions,
  round(100.0 * avg(case when skipped then 1 else 0 end), 1) as skip_pct
from public.answers
group by question_id
order by avg_seconds desc;

-- 4. Funnel.
create or replace view public.v_funnel as
select
  count(*)                                                        as started,
  count(*) filter (where completed_at is not null)                as completed,
  round(100.0 * count(*) filter (where completed_at is not null)
        / nullif(count(*), 0), 1)                                 as completion_pct,
  round(percentile_cont(0.5) within group (
          order by duration_ms) filter (where completed_at is not null)
        / 1000.0)                                                 as median_seconds
from public.sessions;

-- 5. Are Tightrope users abandoning before the result? If so, some copy
--    upstream is shaming them and needs rewriting.
create or replace view public.v_completion_by_archetype as
select
  r.archetype,
  count(*)                                                  as completions,
  round(avg(s.duration_ms) / 1000.0)                        as avg_seconds,
  count(*) filter (where w.id is not null)                  as joined_waitlist,
  count(*) filter (where w.wants_interview)                 as opted_into_interview
from public.results r
join public.sessions s on s.id = r.session_id
left join public.waitlist w on w.session_id = r.session_id
group by r.archetype
order by completions desc;

-- 6. The verbatim corpus — the actual product brief.
create or replace view public.v_verbatims as
select
  a.session_id,
  a.question_id,
  a.value ->> 'value'  as response,
  r.archetype,
  r.hypothesis_signal,
  a.answered_at
from public.answers a
left join public.results r on r.session_id = a.session_id
where a.question_id in ('wish', 'said_no', 'tool_gap')
  and a.value ->> 'kind' = 'text'
  and length(coalesce(a.value ->> 'value', '')) > 2
order by a.answered_at desc;
